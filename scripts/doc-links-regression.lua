-- 壊れたリンク・孤児資料を拒否し、教材のコード例を誤判定しない。
local root = vim.fs.dirname(vim.fs.dirname(vim.fn.fnamemodify(arg[0], ":p")))
local dir = vim.fn.tempname()
vim.fn.mkdir(dir .. "/docs", "p")
local function write(name, lines) vim.fn.writefile(lines, dir .. "/" .. name) end
local function run()
  return vim.system({ vim.v.progpath, "--clean", "--headless", "-l", root .. "/scripts/doc-links.lua", dir },
    { text = true }):wait(5000)
end
local ok, err = pcall(function()
  write("docs/README.md", { "[guide](guide.md)", '[web](https://example.invalid)', "```md", "[example](missing.md)", "```" })
  write("docs/guide.md", { "[page](<page one.html>)", "`[code](missing.md)`" })
  write("docs/page one.html", { '<a href="guide.md#section">back</a>' })
  assert(run().code == 0, "valid graph or fenced example rejected")
  write("docs/guide.md", { "[page](page%20one.html)", "[missing](gone.md)" })
  local result = run()
  assert(result.code ~= 0 and result.stderr:find("missing link: gone.md", 1, true), "missing link passed")
  write("docs/guide.md", { "[page](page%20one.html)" })
  write("docs/orphan.md", { "# orphan" })
  result = run()
  assert(result.code ~= 0 and result.stderr:find("not reachable", 1, true), "orphan passed")
  write("docs/guide.md", { "[page][p]", "[orphan](orphan.md)", "[p]: <page one.html>" })
  assert(run().code == 0, "reference link rejected")
  write("docs/guide.md", { "[page][p]", "[p]: <page one.html>", "[unused]: orphan.md" })
  result = run()
  assert(result.code ~= 0 and result.stderr:find("not reachable", 1, true), "unused definition made orphan reachable")
  write("docs/guide.md", { "[page][]", "[orphan]", "[page]: <page one.html>", "[orphan]: orphan.md" })
  assert(run().code == 0, "collapsed or shortcut reference rejected")
  write("docs/guide.md", { '<a href="page one.html">page</a>', '[orphan](orphan.md)', '<a href="missing.md">missing</a>' })
  result = run()
  assert(result.code ~= 0 and result.stderr:find("missing link: missing.md", 1, true), "Markdown HTML missing link passed")
end)
vim.fn.delete(dir, "rf")
if not ok then io.stderr:write(tostring(err) .. "\n"); os.exit(1) end
io.write("docs regression: missing / orphan / references / HTML / code examples passed\n")
